const dicts = { az, en, ru };

/* {0}, {1} ... şəklində parametr əvəzləməsi; tapılmayan açar az dilinə, sonra açarın özünə düşür */
function translate(locale, key) {
  const args = Array.prototype.slice.call(arguments, 2);
  const d = dicts[locale] || {};
  let text = d[key];
  if (text === undefined) text = az[key];
  if (text === undefined) text = key;
  return text.replace(/\{(\d+)\}/g, function (m, i) {
    return args[i] !== undefined ? String(args[i]) : m;
  });
}

module.exports = { dicts, translate };
